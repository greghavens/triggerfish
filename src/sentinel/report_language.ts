const catalogs = { es: spanish, ko, zh, ja };
export type SentinelReportLanguage = "en" | keyof typeof catalogs;

export function isSentinelReportLanguage(
  value: unknown,
): value is SentinelReportLanguage {
  return value === "en" ||
    (typeof value === "string" && Object.hasOwn(catalogs, value));
}

export function sentinelReportText(language: SentinelReportLanguage) {
  return (
    message: ReportMessage,
    counts: Readonly<Record<string, string | number>> = {},
  ) =>
    (language === "en" ? message : catalogs[language][message]).replace(
      /\{(\w+)\}/g,
      (placeholder, key) =>
        Object.hasOwn(counts, key) ? String(counts[key]) : placeholder,
    );
}
